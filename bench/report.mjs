// Turns bench/results/*.json into bench/RESULTS.md (tables for the README).
// Usage: node bench/report.mjs
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { CATEGORIES, CATEGORY_LABEL } from './score.mjs';

const dir = join(import.meta.dirname, 'results');
const load = (set, kind, tag) => {
  const f = join(dir, `${set}.${kind}.${tag}.json`);
  return existsSync(f) ? JSON.parse(readFileSync(f, 'utf8')) : null;
};
const p = (x) => (Number.isFinite(x) ? `${x.toFixed(1)}%` : 'n/a');
const s = (ms) => `${(ms / 1000).toFixed(2)} s`;

const runs = [
  ['Pattern rules only, before', 'rules', 'v1'],
  ['Pattern rules only, after', 'rules', 'v2'],
  ['Rules + Gemini Nano, before', 'nano', 'v1'],
  ['Rules + Gemini Nano, after', 'nano', 'v2'],
];

function table(set) {
  const rs = runs.map(([name, kind, tag]) => [name, load(set, kind, tag)]).filter(([, r]) => r);
  if (!rs.length) return '';
  const head = `| | ${rs.map(([n]) => n).join(' | ')} |\n|---|${rs.map(() => '---:').join('|')}|`;
  const row = (label, f) => `| ${label} | ${rs.map(([, r]) => f(r)).join(' | ')} |`;
  const lines = [
    head,
    row('**Values hidden (recall)**', (r) => `**${r.summary.overall.hidden}/${r.summary.overall.n} (${p(r.summary.overall.recall)})**`),
    row('**Values with any part in the cloud payload**', (r) => `**${r.summary.overall.reachedCloud}**`),
    row('Precision (hidden things that were personal)', (r) => p(r.summary.overall.precision)),
    row('Messages with nothing personal left', (r) => `${r.summary.cleanMessages}/${r.messages}`),
    ...CATEGORIES.map((c) => row(`Recall: ${CATEGORY_LABEL[c]}`, (r) => {
      const b = r.summary.byCategory[c];
      return b.n ? `${b.hidden}/${b.n} (${p(b.recall)})` : 'n/a';
    })),
    ...['split-number', 'spelled-digits', 'word-name', 'obfuscated-email', 'letter-o-for-zero', 'lowercase-name'].map((g) =>
      row(`Recall in adversarial: ${g}`, (r) => {
        const x = r.summary.groups[`adversarial:${g}`];
        return x ? `${x.hidden}/${x.n}` : 'n/a';
      }),
    ),
    ...['en', 'ms', 'mixed'].map((l) => row(`Recall, ${{ en: 'English', ms: 'Bahasa Melayu', mixed: 'mixed' }[l]} messages`, (r) => p(r.summary.groups[`lang:${l}`]?.recall))),
  ];
  const nano = rs.filter(([, r]) => r.kind === 'nano');
  if (nano.length) {
    lines.push(row('On-device time per message: first call', (r) => (r.latency ? s(r.latency.cold) : '-')));
    lines.push(row('On-device time per message: median / p95 after that', (r) => (r.latency ? `${s(r.latency.warm.median)} / ${s(r.latency.warm.p95)}` : '-')));
    lines.push(row('`generateContent` requests during the run', (r) => (r.network ? String(r.network.generateContentCalls) : '-')));
  }
  return lines.join('\n');
}

const ds = JSON.parse(readFileSync(join(import.meta.dirname, 'dataset.json'), 'utf8'));
const ho = JSON.parse(readFileSync(join(import.meta.dirname, 'heldout.json'), 'utf8'));
const any = load('dataset', 'nano', 'v2') ?? load('dataset', 'nano', 'v1');
const md = `# Redaction benchmark results

Generated by \`node bench/report.mjs\` from \`bench/results/*.json\`. Run it yourself with \`npm run bench\`.

- **Generated set** (\`bench/dataset.json\`): ${ds.messages.length} synthetic Malaysian messages (clinic, HR, bank, school; English, Bahasa Melayu and mixed), ${ds.messages.reduce((n, m) => n + m.labels.length, 0)} labelled personal values, ${ds.messages.filter((m) => m.adversarial).length} adversarial messages. Seeded generator: \`bench/make-dataset.mjs\`.
- **Held-out set** (\`bench/heldout.json\`): ${ho.messages.length} hand-written messages, ${ho.messages.reduce((n, m) => n + m.labels.length, 0)} labelled values, written before any tuning and never used for it.
- **Before** = the rules and prompt as first built. **After** = after looking at the misses on the generated set (see "What changed"). Because the changes were made by looking at the generated set, its "after" numbers are optimistic; the held-out set is the fairer check.
- A value counts as hidden only if every letter and digit of it was replaced. Organisation names are optional: hiding them is neither required nor counted as a mistake.
- Gemini Nano runs: ${any?.chrome ?? 'Google Chrome'}, through Firebase AI Logic (\`InferenceMode.ONLY_ON_DEVICE\`), the app's own \`detect()\`. Every on-device answer reported \`inferenceSource: on_device\`.

## Generated set

${table('dataset')}

## Held-out set

${table('heldout')}

## What changed between "before" and "after"

Everything below was added after reading the misses on the generated set, and is covered by unit tests in \`tests/rules.test.ts\`.

- **Pattern rules** (\`src/rules.ts\`): Malaysian phone numbers in every common format (no separators, \`+60\`, a letter O typed for zero), checked by length per area code; MyKad numbers without dashes or with spaces, accepted only when the date and the place-of-birth code are valid; account and ID numbers after a keyword in English or Bahasa Melayu (\`account\`, \`akaun\`, \`a/c\`, \`staff ID\`, \`no. pekerja\`, \`EPF\`, \`passport\`); digits written as words (\`zero one two\`, \`kosong satu dua\`); emails written as \`name at example dot com\`; dates of birth after a keyword; street addresses that run from a house or lot number to a postcode and town.
- **Name parts** (\`expandNames\` in \`src/redact.ts\`): when a full name is found, its capitalised parts are also hidden where they appear on their own ("Hope Tingang" ... "see Hope today"). Patronymic words (bin, binti, a/l, a/p) and common prefixes are never expanded.
- **On-device answer clean-up** (\`plausible\` in \`src/sulit.ts\`): a "date of birth" with no year, an "address" with no street word or postcode, and times or ages are dropped. Gemini Nano tagged appointment dates as dates of birth and town names as addresses.
- **Prompt** (\`detectorPrompt\` in \`src/sulit.ts\`): says the text may be in Bahasa Melayu or mixed, names Malay, Chinese and Indian name patterns, names that are ordinary words, lowercase names, numbers written as words or split, and lists what not to include.

## Known misses (after)

- Generated set: one split phone number (the first half was hidden, the second sent), one full name, one name part, and the name "Hope" once.
- Held-out set: two addresses only partly hidden (the address rule starts at the house number, so a leading "No" stayed; and the clean-up dropped one fragment, "Asrama Pekerja", that Gemini Nano had marked as an address), one name ("Anand Gopal"), and two numbers with unusual dashes (\`PL-7781-2204\`, \`0123-0045-889-1\`) only partly hidden.
- Precision below 100% comes from money amounts (\`RM 1,349.50\`), "TAC" and class names that Gemini Nano marked as OTHER; they are hidden unnecessarily, not leaked.
- The review step exists because no detector is perfect: before anything is sent, the user sees exactly what will leave and can hide more.
`;
writeFileSync(join(import.meta.dirname, 'RESULTS.md'), md);
console.log(md);
